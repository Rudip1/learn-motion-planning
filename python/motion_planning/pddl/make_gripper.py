#!/usr/bin/env python3
"""Write gripper_n<N>.pddl: N balls in room A to be carried to room B (N = 2, 4, ..., 10)."""
from pathlib import Path

for n in range(2, 11, 2):
    balls = " ".join(f"ball{i}" for i in range(1, n + 1))
    init = " ".join(f"(ball ball{i}) (at ball{i} rooma)" for i in range(1, n + 1))
    goal = " ".join(f"(at ball{i} roomb)" for i in range(1, n + 1))
    text = f"""; Gripper with {n} balls (generated by make_gripper.py). Optimal plan: {6 * n // 2 - 1} actions.
(define (problem gripper-n{n})
  (:domain gripper)
  (:objects rooma roomb {balls} left right)
  (:init (room rooma) (room roomb) (gripper left) (gripper right) (at-robby rooma) (free left) (free right)
         {init})
  (:goal (and {goal})))
"""
    (Path(__file__).parent / f"gripper_n{n}.pddl").write_text(text)
